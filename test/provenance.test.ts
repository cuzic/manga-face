import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {test} from 'node:test';
import {PRESETS} from '../src/index.ts';

const text = fs.readFileSync(path.join(import.meta.dirname, '../PROVENANCE.md'), 'utf8');

test('every part named in the source has a row in PROVENANCE.md (a PR that adds a part adds its row)', () => {
  for (const part of ['face outline', 'eyes', 'brows', 'mouths', 'nose', 'hair templates', 'presets', 'body, neck, ears']) {
    assert.ok(text.split('\n').some(l => l.startsWith(`| ${part}`)), `no row for: ${part}`);
  }
});

test('every row says how it was written, and the method is one the rights rule allows', () => {
  const rows = text.split('\n').filter(l => l.startsWith('| ') && !l.startsWith('| Part') && !l.startsWith('| ---'));
  assert.ok(rows.length >= 8);
  for (const r of rows) assert.match(r, /as code/, r);
  assert.doesNotMatch(rows.join('\n'), /(generated by|traced from|reference image)/i);
});

test('the presets are listed: a preset added to PRESETS needs the provenance row to be reviewed (the count is pinned)', () => {
  assert.equal(Object.keys(PRESETS).length, 14);
});
